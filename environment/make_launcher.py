#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
生成 Windows 批处理启动器（ASCII + CRLF）
=========================================

为什么要用脚本生成，而不是直接写 .bat 文件
------------------------------------------
Windows cmd.exe 解析批处理有两个硬性要求，编辑器和工具链经常破坏它们：

1. **必须 CRLF 换行**。LF 换行会让 cmd 把相邻两行当成同一条命令，
   报「命令语法不正确」或「系统找不到指定的路径」——这正是本次故障的原因。
2. **代码页**。文件含中文时，默认 GBK 控制台下 UTF-8 中文会乱码，
   甚至因为在多字节字符中间断行而解析失败。

对策：批处理只写 ASCII 且强制 CRLF；所有中文提示交给同目录的 `welcome.py`
（Python 能按控制台实际代码页编码输出，稳得多）。

用法
----
    python make_launcher.py            # 生成/覆盖 进入MICourse环境.bat
    python make_launcher.py --check    # 只检查现有文件是否符合 ASCII+CRLF

作者：何刚  NNIP LAB @ SWUST
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE / "进入MICourse环境.bat"

# 注意：全部 ASCII，不含任何中文；变量展开在 cmd 里完成，Python 不参与
BAT = r"""@echo off
REM ===========================================================================
REM  MICourse course environment launcher
REM  Generated by make_launcher.py -- do not edit by hand.
REM  Requirements: ASCII only, CRLF line endings. Both are mandatory for cmd.exe.
REM ===========================================================================
setlocal

set "CENV=%USERPROFILE%\.conda\envs\MICourse"
if not exist "%CENV%\python.exe" (
    echo.
    echo [ERROR] MICourse environment not found.
    echo         Expected: %CENV%\python.exe
    echo         Run this first:  bash rebuild_env.sh
    echo.
    pause
    exit /b 1
)

REM Isolate user-level site-packages; otherwise stale numpy/pandas shadow the env.
set "PYTHONNOUSERSITE=1"
set "CONDA_DEFAULT_ENV=MICourse"

REM Prepend the environment so bare "python" / "jupyter" resolve to MICourse.
set "PATH=%CENV%;%CENV%\Library\mingw-w64\bin;%CENV%\Library\usr\bin;%CENV%\Library\bin;%CENV%\Scripts;%PATH%"

cd /d "%~dp0"

REM Chinese banner is printed from Python to avoid code page problems.
if not exist "%~dp0welcome.py" (
    echo [WARN] welcome.py not found, banner skipped.
) else (
    "%CENV%\python.exe" "%~dp0welcome.py"
)

REM Keep the window open with the environment active.
cmd /k

endlocal
"""


def check(path: Path) -> int:
    if not path.exists():
        print(f"[x] 不存在：{path}")
        return 1
    raw = path.read_bytes()
    problems = []

    if b"\r\n" not in raw:
        problems.append("缺少 CRLF 换行（cmd.exe 会解析失败）")
    lone_lf = raw.replace(b"\r\n", b"").count(b"\n")
    if lone_lf:
        problems.append(f"存在 {lone_lf} 处孤立 LF 换行")

    non_ascii = [(i, b) for i, b in enumerate(raw) if b > 127]
    if non_ascii:
        problems.append(f"含 {len(non_ascii)} 个非 ASCII 字节（会乱码/断行）")

    if problems:
        print(f"[!] {path.name} 不符合要求：")
        for p in problems:
            print(f"    - {p}")
        return 1
    print(f"[ok] {path.name}：ASCII + CRLF，符合 cmd.exe 要求（{len(raw)} 字节）")
    return 0


def make(path: Path) -> int:
    # 强制 CRLF：先把可能存在的 CR 去掉，再逐行加 \r\n
    normalized = BAT.replace("\r\n", "\n").replace("\r", "\n")
    text = "\r\n".join(normalized.split("\n"))
    data = text.encode("ascii")          # 若非 ASCII 会在这里抛错，等于自带校验
    path.write_bytes(data)
    print(f"[ok] 已生成：{path}（{len(data)} 字节，ASCII + CRLF）")
    return check(path)


def main() -> int:
    ap = argparse.ArgumentParser(description="生成/校验 MICourse 批处理启动器")
    ap.add_argument("--check", action="store_true", help="只校验现有文件")
    args = ap.parse_args()
    return check(TARGET) if args.check else make(TARGET)


if __name__ == "__main__":
    sys.exit(main())
